#!/usr/bin/env python3
"""
Physics Validation for PI-Mamba V12

Measures polymer-physics observables of backbones generated by a trained
model and compares them with the same observables of real structures:

1. Radius of gyration and end-to-end distance as a function of chain length,
   with the fitted scaling exponent R_g ~ N^nu.
2. Learned relaxation time tau per secondary-structure class.

Usage:
    python scripts/validate_physics.py --checkpoint checkpoints/best_model.pt \
        --data_dir Distilled_trainset --output_dir figures
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter, NullFormatter
import numpy as np
import torch

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

from src.data import CADataset
from src.model_io import load_checkpoint
from src.rouse_physics import compute_end_to_end_distance, compute_radius_of_gyration
from sweep_utils import tau_by_secondary_structure


def fit_exponent(lengths, values):
    """Slope of log(values) against log(lengths)."""
    if len(lengths) < 2:
        return None
    return float(np.polyfit(np.log(lengths), np.log(values), 1)[0])


def validate_physics(args):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Running validation on {device}")

    model, ckpt = load_checkpoint(args.checkpoint, device=device)
    lengths = [int(v) for v in args.lengths.split(",")]

    # 1. Scaling of generated structures
    generated = {'L': [], 'Ree': [], 'Rg': [], 'Rg_std': []}
    print("\nMeasuring polymer scaling of generated structures...")
    generator = torch.Generator(device=device).manual_seed(args.seed)
    for L in lengths:
        samples = model.sample(length=L, n_samples=args.n_samples, n_steps=args.n_steps,
                               device=device, generator=generator)
        ree = compute_end_to_end_distance(samples).cpu().numpy()
        rg = compute_radius_of_gyration(samples).cpu().numpy()
        generated['L'].append(L)
        generated['Ree'].append(float(ree.mean()))
        generated['Rg'].append(float(rg.mean()))
        generated['Rg_std'].append(float(rg.std()))
        print(f"L={L}: <Ree>={ree.mean():.2f} A, <Rg>={rg.mean():.2f} ± {rg.std():.2f} A")

    # Same observables on real structures
    reference = {'L': [], 'Ree': [], 'Rg': []}
    if args.data_dir:
        dataset = CADataset(args.data_dir)
        by_length = defaultdict(list)
        for ca in dataset.coords:
            by_length[len(ca)].append(ca)
        for L in sorted(by_length):
            if len(by_length[L]) < args.min_reference:
                continue
            ca = torch.stack(by_length[L])
            reference['L'].append(L)
            reference['Ree'].append(compute_end_to_end_distance(ca).mean().item())
            reference['Rg'].append(compute_radius_of_gyration(ca).mean().item())

    results = {
        "checkpoint": str(args.checkpoint),
        "generated": generated,
        "reference": reference,
        "rg_exponent_generated": fit_exponent(generated['L'], generated['Rg']),
        "rg_exponent_reference": fit_exponent(reference['L'], reference['Rg']),
    }
    print(f"\nR_g ~ N^nu: generated nu = {results['rg_exponent_generated']}, "
          f"reference nu = {results['rg_exponent_reference']}")
    print("For comparison: 1/3 compact globule, 1/2 ideal (Rouse) chain, 0.588 self-avoiding walk")

    # 2. Relaxation time per secondary-structure class
    if args.data_dir and ckpt["config"].get("model", "pi_mamba") == "pi_mamba":
        results["tau"] = tau_by_secondary_structure(args.checkpoint, args.data_dir)
        print("Mean learned tau per residue class: "
              + ", ".join(f"{k}={v:.4f}" for k, v in results["tau"].items() if v is not None))

    # Plot
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.5))
    for ax, key, label in ((axes[0], 'Rg', 'Radius of gyration (Å)'),
                           (axes[1], 'Ree', 'End-to-end distance (Å)')):
        ax.loglog(generated['L'], generated[key], 'o-', label='Generated')
        if reference['L']:
            ax.loglog(reference['L'], reference[key], 's--', label='Reference structures')
        ax.set_xlabel('Chain length N')
        ax.set_ylabel(label)

    # Guide lines for the compact-globule and ideal-chain exponents
    L_line = np.array([min(generated['L']), max(generated['L'])], dtype=float)
    for exponent, color, label in ((1 / 3, 'black', r'$N^{1/3}$'), (0.5, 'gray', r'$N^{1/2}$')):
        anchor = generated['Rg'][0] / L_line[0] ** exponent
        axes[0].loglog(L_line, anchor * L_line ** exponent, color=color, ls=':', label=label)

    # Plain numbers on the log axes, with x ticks at the measured lengths.
    # This has to come after the last loglog call, which resets the formatters.
    plain = FuncFormatter(lambda v, _: f"{v:g}")
    for ax in axes:
        ax.set_xticks(sorted(set(generated['L']) | set(reference['L'])))
        ax.xaxis.set_major_formatter(plain)
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.yaxis.set_major_formatter(plain)
        ax.yaxis.set_minor_formatter(plain)
        ax.legend()
    fig.tight_layout()
    out_path = out_dir / "physics_scaling.png"
    fig.savefig(out_path, dpi=150)
    print(f"Saved scaling plot to {out_path}")

    with open(out_dir / "physics_validation.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"Saved results to {out_dir / 'physics_validation.json'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--checkpoint", type=str, required=True, help="checkpoint from scripts/train.py")
    parser.add_argument("--data_dir", type=str, default=str(REPO_ROOT / "Distilled_trainset"),
                        help="reference structures (set to '' to skip the comparison)")
    parser.add_argument("--output_dir", type=str, default="figures")
    parser.add_argument("--lengths", type=str, default="50,100,150,200,300")
    parser.add_argument("--n_samples", type=int, default=32)
    parser.add_argument("--n_steps", type=int, default=100)
    parser.add_argument("--min_reference", type=int, default=50,
                        help="minimum number of reference chains of one length")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    validate_physics(args)
